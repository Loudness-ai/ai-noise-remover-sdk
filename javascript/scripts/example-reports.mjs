import { mkdir, writeFile, readFile, mkdtemp, rm } from "node:fs/promises";
import { createHash } from "node:crypto";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const {
  analyze,
  inspect,
  evaluate,
  examplePolicy,
  compare,
  batch,
  benchmark,
  doctor,
  renderHtml,
} = require("../dist/cjs/index.js");
const folder = await mkdtemp(join(tmpdir(), "audit-examples-"));
await mkdir("examples/reports", { recursive: true });
try {
  const silent = join(folder, "silence.wav");
  const generated = spawnSync("ffmpeg", [
    "-nostdin",
    "-v",
    "error",
    "-f",
    "lavfi",
    "-i",
    "anullsrc=r=48000:cl=mono",
    "-t",
    "2",
    "-c:a",
    "pcm_s16le",
    silent,
  ]);
  if (generated.status !== 0) throw Error(generated.stderr.toString());
  const tone = "demo/sample.wav";
  const analysis = await analyze(tone, { maxPoints: 64 });
  const versions = await doctor();
  const measured = await benchmark(
    {
      schemaVersion: 1,
      fixtures: [
        {
          path: tone,
          sha256: createHash("sha256")
            .update(await readFile(tone))
            .digest("hex"),
          license: "CC0-1.0",
        },
      ],
      processors: [
        {
          name: "PCM conversion",
          executable: "ffmpeg",
          args: [
            "-nostdin",
            "-v",
            "error",
            "-i",
            "{input}",
            "-c:a",
            "pcm_s16le",
            "{output}",
          ],
          version: versions.versions.ffmpeg,
          settings: { codec: "pcm_s16le" },
        },
      ],
      repetitions: 2,
      warmup: 0,
      comparison: true,
    },
    { allowExecution: true, maxPoints: 64 },
  );
  const reports = {
    analysis,
    inspection: await inspect(tone),
    silent: await analyze(silent, { maxPoints: 64 }),
    "policy-failure": evaluate(analysis, examplePolicy),
    comparison: await compare(tone, tone, { maxPoints: 64 }),
    batch: await batch([tone, tone], { concurrency: 3, maxPoints: 64 }),
    benchmark: measured,
  };
  for (const [name, report] of Object.entries(reports)) {
    await writeFile(
      `examples/reports/${name}.json`,
      JSON.stringify(report, null, 2) + "\n",
    );
    await writeFile(`examples/reports/${name}.html`, renderHtml(report));
  }
  const invalid = join(folder, "invalid.wav");
  await writeFile(invalid, "invalid media");
  try {
    await analyze(invalid);
    throw Error("Expected invalid media rejection");
  } catch (e) {
    if (!e.code) throw e;
    await writeFile(
      "examples/reports/invalid-error.json",
      JSON.stringify(e.toJSON(), null, 2) + "\n",
    );
  }
  await writeFile(
    "examples/reports/README.md",
    "# Example reports\n\nGenerated by `node scripts/example-reports.mjs`. Audio is synthetic CC0-1.0. These reports show structure and example policy outcomes; benchmark timings describe the recorded local run, not a product performance promise. Invalid media produces a structured error rather than a successful partial analysis. Reports contain basenames and no customer media.\n",
  );
} finally {
  await rm(folder, { recursive: true, force: true });
}
